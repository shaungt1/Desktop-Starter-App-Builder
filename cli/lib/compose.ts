/**
 * Composition: turns a base template plus a list of modules into a working
 * application. Module code lives in its own folder; composition only writes
 * the small "registry" files that import the enabled modules, merges package
 * manifests and records what was installed.
 *
 * The same functions are used by `create` (new app) and `module add`
 * (existing generated app), so both paths produce identical files.
 */
import fs from "node:fs";
import path from "node:path";
import {
  type BaseId,
  type Catalog,
  findModule,
  type ModuleImplementation,
  type PackagePatch,
  type VariantImplementation,
} from "./catalog.ts";
import { copyTree, readJson, writeJson, writeText } from "./files.ts";
import { info, UserError } from "./log.ts";
import { BUILDER_ROOT, PROVENANCE_FILE } from "./paths.ts";
import type { ProjectPlan } from "./plan.ts";

export const GENERATED_HEADER =
  "Generated by Desktop Starter App Builder from the enabled modules. Do not edit by hand; run the builder's `module add` command instead.";

export interface Provenance {
  builder: { name: string; version: string; commit?: string };
  createdAt: string;
  updatedAt: string;
  base: BaseId;
  profile: string;
  modules: string[];
  plan: ProjectPlan;
}

interface PackageManifest {
  dependencies?: Record<string, string>;
  devDependencies?: Record<string, string>;
  [key: string]: unknown;
}

export function camelCase(id: string): string {
  return id.replace(/-([a-z0-9])/gu, (_, letter: string) => letter.toUpperCase());
}

export function snakeCase(id: string): string {
  return id.replaceAll("-", "_");
}

function implementationFor(catalog: Catalog, base: BaseId, id: string): ModuleImplementation | undefined {
  return findModule(catalog, id).implementations[base];
}

/** Copies one module's files into the app. Existing files are never replaced. */
export function copyModuleFiles(catalog: Catalog, base: BaseId, id: string, appRoot: string): void {
  const implementation = implementationFor(catalog, base, id);
  if (!implementation) {
    return;
  }
  const report = copyTree(path.join(BUILDER_ROOT, implementation.overlay), appRoot, "skip-existing");
  if (report.skipped.length > 0) {
    info(`kept ${report.skipped.length} existing file(s) for module ${id}`);
  }
}

/** Adds module dependencies to package.json without changing versions already present. */
export function mergePackageManifest(catalog: Catalog, base: BaseId, modules: string[], appRoot: string): void {
  const file = path.join(appRoot, "package.json");
  const manifest = readJson<PackageManifest>(file);
  manifest.dependencies ??= {};
  manifest.devDependencies ??= {};
  for (const id of modules) {
    const implementation = implementationFor(catalog, base, id);
    for (const [name, version] of Object.entries(implementation?.dependencies ?? {})) {
      manifest.dependencies[name] ??= version;
    }
    for (const [name, version] of Object.entries(implementation?.devDependencies ?? {})) {
      manifest.devDependencies[name] ??= version;
    }
  }
  manifest.dependencies = sortRecord(manifest.dependencies);
  manifest.devDependencies = sortRecord(manifest.devDependencies);
  writeJson(file, manifest);
}

function sortRecord(record: Record<string, string>): Record<string, string> {
  return Object.fromEntries(Object.entries(record).sort(([a], [b]) => a.localeCompare(b)));
}

/** Sorts import lines by their source the way Biome orders them ("../" before "./", then alphabetical). */
function sortedImports(lines: string[]): string[] {
  const source = (line: string) => line.slice(line.lastIndexOf(" from ") + 7);
  return [...lines].sort((a, b) => (source(a) < source(b) ? -1 : source(a) > source(b) ? 1 : 0));
}

/** Biome's line width in generated apps; registries are written already formatted to it. */
const LINE_WIDTH = 120;

/** Renders `prefix[items];` on one line when it fits, otherwise one item per line (Biome's layout). */
function arrayStatement(prefix: string, items: string[]): string {
  const single = `${prefix}[${items.join(", ")}];`;
  if (items.length === 0 || single.length <= LINE_WIDTH) {
    return single;
  }
  return `${prefix}[\n${items.map((item) => `  ${item},`).join("\n")}\n];`;
}

function typescriptFile(imports: string[], body: string[]): string {
  return [`// ${GENERATED_HEADER}`, "", ...sortedImports(imports), "", ...body, ""].join("\n");
}

/** Writes the Electron registry files that import enabled modules. */
export function writeElectronRegistries(catalog: Catalog, modules: string[], appRoot: string): void {
  const main = modules.filter((id) => implementationFor(catalog, "electron", id)?.mainModule);
  const features = modules.filter((id) => implementationFor(catalog, "electron", id)?.rendererFeature);

  const registry = typescriptFile(
    [
      'import type { MainModule } from "./types";',
      ...main.map((id) => `import { mainModule as ${camelCase(id)}Module } from "./${id}";`),
    ],
    [
      "/** Main-process modules started by src/main/main.ts, in dependency order. */",
      arrayStatement(
        "export const enabledModules: readonly MainModule[] = ",
        main.map((id) => `${camelCase(id)}Module`),
      ),
    ],
  );
  writeText(path.join(appRoot, "src/main/modules/registry.ts"), registry);

  const router = typescriptFile(
    [
      'import { coreRouter } from "./core-router";',
      ...main.map((id) => `import { mainModule as ${camelCase(id)}Module } from "../modules/${id}";`),
    ],
    [
      "/** Every procedure the renderer may call. The renderer's client type is derived from this object. */",
      "export const router = {",
      "  ...coreRouter,",
      ...main.map((id) => `  ${camelCase(id)}: ${camelCase(id)}Module.router,`),
      "};",
      "",
      "export type AppRouter = typeof router;",
    ],
  );
  writeText(path.join(appRoot, "src/main/ipc/router.ts"), router);

  writeFeatureRegistry(features, path.join(appRoot, "src/renderer/features/registry.ts"));
}

function writeFeatureRegistry(features: string[], file: string): void {
  const content = typescriptFile(
    [
      'import type { RendererFeature } from "./types";',
      ...features.map((id) => `import { feature as ${camelCase(id)}Feature } from "./${id}";`),
    ],
    [
      "/** Feature panels shown on the home screen, one per enabled module that has a user interface. */",
      arrayStatement(
        "export const features: readonly RendererFeature[] = ",
        features.map((id) => `${camelCase(id)}Feature`),
      ),
    ],
  );
  writeText(file, content);
}

/**
 * Writes the extension's generated files: the background-module registry that
 * entrypoints/background.ts runs, and the permissions the enabled modules need,
 * which wxt.config.ts merges into the manifest.
 */
export function writeExtensionRegistries(catalog: Catalog, modules: string[], appRoot: string): void {
  const background = modules.filter((id) => implementationFor(catalog, "extension", id)?.backgroundModule);
  const registry = typescriptFile(
    [
      'import type { BackgroundModule } from "./types";',
      ...background.map((id) => `import { backgroundModule as ${camelCase(id)}Module } from "./${id}/background";`),
    ],
    [
      "/** Background modules started by entrypoints/background.ts, in dependency order. */",
      arrayStatement(
        "export const enabledModules: readonly BackgroundModule[] = ",
        background.map((id) => `${camelCase(id)}Module`),
      ),
    ],
  );
  writeText(path.join(appRoot, "src/modules/registry.ts"), registry);

  const permissions = new Set<string>();
  const hostPermissions = new Set<string>();
  for (const id of modules) {
    const implementation = implementationFor(catalog, "extension", id);
    for (const permission of implementation?.permissions ?? []) permissions.add(permission);
    for (const host of implementation?.hostPermissions ?? []) hostPermissions.add(host);
  }
  writeJson(path.join(appRoot, "src/permissions.generated.json"), {
    permissions: [...permissions].sort(),
    host_permissions: [...hostPermissions].sort(),
  });
}

/** Writes the Tauri Rust module registry, the frontend feature registry and Cargo dependencies. */
export function writeTauriRegistries(catalog: Catalog, modules: string[], appRoot: string): void {
  const rust = modules
    .map((id) => ({ id, implementation: implementationFor(catalog, "tauri", id) }))
    .filter((entry) => entry.implementation?.rustModule);
  const features = modules.filter((id) => implementationFor(catalog, "tauri", id)?.rendererFeature);

  const commands = rust.flatMap(
    (entry) =>
      entry.implementation?.commands?.map((command) => `${entry.implementation?.rustModule}::${command}`) ?? [],
  );
  const coreCommands = ["crate::commands::app_info", "crate::commands::open_external"];

  const lines = [
    `// ${GENERATED_HEADER}`,
    "",
    ...rust.map((entry) => `pub mod ${entry.implementation?.rustModule};`),
    "",
    "/// Registers every enabled module's plugins on the builder.",
    "pub fn register<R: tauri::Runtime>(builder: tauri::Builder<R>) -> tauri::Builder<R> {",
    ...rust.map((entry) => `    let builder = ${entry.implementation?.rustModule}::register(builder);`),
    "    builder",
    "}",
    "",
    "/// Runs every enabled module's start-up work once the app exists.",
    "pub fn setup<R: tauri::Runtime>(app: &mut tauri::App<R>) -> Result<(), Box<dyn std::error::Error>> {",
    ...rust
      .filter((entry) => entry.implementation?.rustSetup)
      .map((entry) => `    ${entry.implementation?.rustModule}::setup(app)?;`),
    "    let _ = app;",
    "    Ok(())",
    "}",
    "",
    "/// The single command handler: core commands plus every enabled module's commands.",
    "pub fn handler<R: tauri::Runtime>() -> impl Fn(tauri::ipc::Invoke<R>) -> bool + Send + Sync + 'static {",
    `    tauri::generate_handler![${[...coreCommands, ...commands].join(", ")}]`,
    "}",
    "",
  ];
  writeText(path.join(appRoot, "src-tauri/src/modules/mod.rs"), lines.join("\n"));

  writeFeatureRegistry(features, path.join(appRoot, "src/features/registry.ts"));
  enableWorkflowLines(modules, appRoot);
  mergeCargoDependencies(catalog, modules, appRoot);
  mergeTauriConf(catalog, modules, appRoot);
}

/**
 * Workflow lines that only make sense with a module are shipped commented out
 * and marked "# @module:<id>"; this uncomments them once the module is enabled.
 */
function enableWorkflowLines(modules: string[], appRoot: string): void {
  const folder = path.join(appRoot, ".github", "workflows");
  if (!fs.existsSync(folder)) {
    return;
  }
  for (const name of fs.readdirSync(folder)) {
    const file = path.join(folder, name);
    const original = fs.readFileSync(file, "utf8");
    const updated = original.replace(
      /^(\s*)# (.*?) # @module:([a-z0-9-]+)$/gmu,
      (line, indent: string, content: string, id: string) => (modules.includes(id) ? `${indent}${content}` : line),
    );
    if (updated !== original) {
      fs.writeFileSync(file, updated);
    }
  }
}

const CARGO_MARKER = "# @dsab:module-dependencies";

function escapeRegExp(text: string): string {
  return text.replace(/[.*+?^${}()|[\]\\]/gu, "\\$&");
}

/** Adds missing features to an existing `crate = { ..., features = [...] }` line. */
function addCargoFeatures(cargo: string, crate: string, features: string[]): string {
  const line = new RegExp(
    `^(${escapeRegExp(crate)}\\s*=\\s*\\{[^\\n]*?features\\s*=\\s*\\[)([^\\]]*)(\\][^\\n]*)$`,
    "mu",
  );
  const match = cargo.match(line);
  if (!match) {
    throw new UserError(
      `Cannot add features ${features.join(", ")} to ${crate}: write it as ${crate} = { version = "...", features = [] }.`,
    );
  }
  const existing = (match[2] ?? "")
    .split(",")
    .map((item) => item.trim().replaceAll('"', ""))
    .filter(Boolean);
  const merged = [...new Set([...existing, ...features])].map((feature) => `"${feature}"`).join(", ");
  return cargo.replace(line, `$1${merged}$3`);
}

function mergeCargoDependencies(catalog: Catalog, modules: string[], appRoot: string): void {
  const file = path.join(appRoot, "src-tauri/Cargo.toml");
  let cargo = fs.readFileSync(file, "utf8");
  if (!cargo.includes(CARGO_MARKER)) {
    throw new UserError(`src-tauri/Cargo.toml is missing the "${CARGO_MARKER}" line the builder appends after.`);
  }
  const additions: string[] = [];
  for (const id of modules) {
    for (const [crate, spec] of Object.entries(implementationFor(catalog, "tauri", id)?.cargo ?? {})) {
      const present = new RegExp(`^${escapeRegExp(crate)}\\s*=`, "mu").test(cargo);
      if (present) {
        if (spec.features?.length) {
          cargo = addCargoFeatures(cargo, crate, spec.features);
        }
        continue;
      }
      if (additions.some((line) => line.startsWith(`${crate} =`))) {
        continue;
      }
      const parts = [`version = "${spec.version}"`];
      if (spec.defaultFeatures === false) {
        parts.push("default-features = false");
      }
      if (spec.features?.length) {
        parts.push(`features = [${spec.features.map((feature) => `"${feature}"`).join(", ")}]`);
      }
      additions.push(`${crate} = { ${parts.join(", ")} }`);
    }
  }
  if (additions.length > 0) {
    cargo = cargo.replace(CARGO_MARKER, [CARGO_MARKER, ...additions].join("\n"));
  }
  fs.writeFileSync(file, cargo);
}

type JsonObject = Record<string, unknown>;

function isObject(value: unknown): value is JsonObject {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

/** Deep-merges `patch` into `target`; arrays are combined without duplicates. */
export function deepMerge(target: JsonObject, patch: JsonObject): JsonObject {
  const result: JsonObject = { ...target };
  for (const [key, value] of Object.entries(patch)) {
    const current = result[key];
    if (isObject(current) && isObject(value)) {
      result[key] = deepMerge(current, value);
    } else if (Array.isArray(current) && Array.isArray(value)) {
      result[key] = [
        ...current,
        ...value.filter((item) => !current.some((existing) => JSON.stringify(existing) === JSON.stringify(item))),
      ];
    } else {
      result[key] = value;
    }
  }
  return result;
}

/** Applies every enabled module's `tauriConf` patch to src-tauri/tauri.conf.json. */
function mergeTauriConf(catalog: Catalog, modules: string[], appRoot: string): void {
  const file = path.join(appRoot, "src-tauri/tauri.conf.json");
  let conf = readJson<JsonObject>(file);
  for (const id of modules) {
    const patch = implementationFor(catalog, "tauri", id)?.tauriConf;
    if (patch) {
      conf = deepMerge(conf, patch);
    }
  }
  writeJson(file, conf);
}

/** Writes app.config.json: the non-secret runtime configuration both processes read. */
export function writeAppConfig(plan: ProjectPlan, appRoot: string): void {
  writeJson(path.join(appRoot, "app.config.json"), {
    name: plan.name,
    appId: plan.appId,
    scheme: plan.scheme,
    version: plan.version,
    profile: plan.profile,
    frontend: plan.frontend,
    ui: plan.ui,
    targets: plan.targets,
    remoteUrl: plan.remoteUrl ?? null,
    allowedOrigins: plan.allowedOrigins,
    repository: plan.repository ?? null,
    modules: plan.modules,
    moduleOptions: plan.moduleOptions,
  });
}

export function readProvenance(appRoot: string): Provenance {
  const file = path.join(appRoot, PROVENANCE_FILE);
  if (!fs.existsSync(file)) {
    throw new UserError(`${appRoot} was not generated by this builder (no ${PROVENANCE_FILE}).`);
  }
  return readJson<Provenance>(file);
}

export function writeProvenance(appRoot: string, provenance: Provenance): void {
  writeJson(path.join(appRoot, PROVENANCE_FILE), provenance);
}

/**
 * Applies a frontend or interface-kit variant to a freshly copied app:
 * deletes the template files it replaces, copies its overlays, and patches
 * package.json, JSON config files, tauri.conf.json and .gitignore.
 */
export function applyVariant(variant: VariantImplementation, appRoot: string, rendererDir: string): void {
  for (const file of variant.remove ?? []) {
    fs.rmSync(path.join(appRoot, file), { force: true });
  }
  for (const overlay of variant.overlays) {
    const destination = overlay.into === "renderer" ? path.join(appRoot, rendererDir) : appRoot;
    copyTree(path.join(BUILDER_ROOT, overlay.from), destination, "overwrite");
  }
  if (variant.packageJson) {
    patchPackageManifest(variant.packageJson, appRoot);
  }
  for (const [file, patch] of Object.entries(variant.jsonPatches ?? {})) {
    const absolute = path.join(appRoot, file);
    writeJson(absolute, deepMerge(readJson<JsonObject>(absolute), patch));
  }
  if (variant.tauriConf) {
    const file = path.join(appRoot, "src-tauri/tauri.conf.json");
    writeJson(file, deepMerge(readJson<JsonObject>(file), variant.tauriConf));
  }
  for (const insert of variant.textInserts ?? []) {
    const file = path.join(appRoot, insert.into === "renderer" ? rendererDir : "", insert.file);
    const content = fs.readFileSync(file, "utf8");
    if (content.includes(insert.text)) {
      continue;
    }
    if (!content.includes(insert.after)) {
      throw new UserError(`Cannot find "${insert.after}" in ${file} to insert after.`);
    }
    fs.writeFileSync(file, content.replace(insert.after, `${insert.after}\n${insert.text}`));
  }
  if (variant.gitignore?.length) {
    const file = path.join(appRoot, ".gitignore");
    const existing = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "";
    const lines = existing.split(/\r?\n/u);
    const missing = variant.gitignore.filter((line) => !lines.includes(line));
    if (missing.length > 0) {
      fs.writeFileSync(file, `${existing.replace(/\n*$/u, "\n")}${missing.join("\n")}\n`);
    }
  }
}

function patchPackageManifest(patch: PackagePatch, appRoot: string): void {
  const file = path.join(appRoot, "package.json");
  const manifest = readJson<PackageManifest & { scripts?: Record<string, string> }>(file);
  manifest.scripts = { ...manifest.scripts, ...patch.scripts };
  manifest.dependencies = { ...manifest.dependencies, ...patch.dependencies };
  manifest.devDependencies = { ...manifest.devDependencies, ...patch.devDependencies };
  for (const name of patch.removeDependencies ?? []) {
    delete manifest.dependencies[name];
    delete manifest.devDependencies[name];
  }
  manifest.dependencies = sortRecord(manifest.dependencies);
  manifest.devDependencies = sortRecord(manifest.devDependencies);
  writeJson(file, manifest);
}

/** Command spellings for each supported package manager, used to rewrite scripts and docs. */
const PACKAGE_MANAGER_COMMANDS: Record<string, Array<[RegExp, string]>> = {
  npm: [
    [/^.*# @bun-only\n/gmu, ""],
    [/\bbun scripts\//gu, "node scripts/"],
    [/\bbun install --frozen-lockfile\b/gu, "npm ci"],
    [/\bbun run\b/gu, "npm run"],
    [/\bbun install\b/gu, "npm install"],
    [/\bbun add -d\b/gu, "npm install -D"],
    [/\bbun add\b/gu, "npm install"],
    [/\bbun remove\b/gu, "npm uninstall"],
    [/\bbunx\b/gu, "npx"],
  ],
};

/**
 * Rewrites Bun commands in the app's scripts, configuration and instructions
 * to the plan's package manager. The bundled reference docs under docs/ show
 * both spellings and are left as they are.
 */
export function applyPackageManager(packageManager: string, appRoot: string, files: string[]): void {
  // Lines marked "# @bun-only" (workflow steps that install Bun) are kept for Bun and dropped otherwise.
  const rules = PACKAGE_MANAGER_COMMANDS[packageManager] ?? [[/ # @bun-only$/gmu, ""]];
  if (packageManager !== "bun") {
    fs.rmSync(path.join(appRoot, "bunfig.toml"), { force: true });
  }
  const rewritable = /\.(json|md|ts|mts|tsx|rs|yml|yaml|example)$/u;
  for (const file of files) {
    if (file.startsWith("docs/") || !rewritable.test(file) || !fs.existsSync(path.join(appRoot, file))) {
      continue;
    }
    const absolute = path.join(appRoot, file);
    const original = fs.readFileSync(absolute, "utf8");
    const updated = rules.reduce((text, [pattern, replacement]) => text.replace(pattern, replacement), original);
    if (updated !== original) {
      fs.writeFileSync(absolute, updated);
    }
  }
  if (packageManager !== "bun") {
    const manifestFile = path.join(appRoot, "package.json");
    const manifest = readJson<JsonObject>(manifestFile);
    delete manifest.trustedDependencies;
    writeJson(manifestFile, manifest);
  }
}

/** Scripts added to a Tauri app for each mobile target in the plan. */
const MOBILE_SCRIPTS: Record<string, Record<string, string>> = {
  android: {
    "android:init": "tauri android init",
    "android:dev": "tauri android dev",
    "android:build": "tauri android build",
  },
  ios: {
    "ios:init": "tauri ios init",
    "ios:dev": "tauri ios dev",
    "ios:build": "tauri ios build",
  },
};

/**
 * Prepares a Tauri app for its Android/iOS targets. The native projects
 * (src-tauri/gen/android, src-tauri/gen/apple) are created on a machine with
 * the mobile SDKs by the `android:init` / `ios:init` scripts, because they
 * need those SDKs; docs/tauri/14-mobile.md lists the steps.
 */
export function applyTargets(targets: readonly string[], appRoot: string): void {
  const scripts = Object.assign({}, ...targets.map((target) => MOBILE_SCRIPTS[target] ?? {}));
  if (Object.keys(scripts).length > 0) {
    patchPackageManifest({ scripts }, appRoot);
  }
}

/**
 * Copies the reference docs and setup scripts listed in the catalog into the
 * app, so a person or agent working in the app (with no access to the builder)
 * still has the setup steps, plugin guides, signing and release instructions.
 * Existing files are kept. Returns the copied paths relative to the app.
 */
export function copyBundledFiles(entries: ReadonlyArray<{ from: string; to: string }>, appRoot: string): string[] {
  const copied: string[] = [];
  for (const entry of entries) {
    const source = path.join(BUILDER_ROOT, entry.from);
    if (fs.statSync(source).isDirectory()) {
      const report = copyTree(source, path.join(appRoot, entry.to), "skip-existing");
      copied.push(...report.written.map((file) => `${entry.to}/${file}`));
      continue;
    }
    const destination = path.join(appRoot, entry.to);
    if (fs.existsSync(destination)) {
      continue;
    }
    fs.mkdirSync(path.dirname(destination), { recursive: true });
    fs.copyFileSync(source, destination);
    fs.chmodSync(destination, fs.statSync(source).mode);
    copied.push(entry.to);
  }
  return copied;
}

